-- Plain text date columns retain the exact original SQLite contents, including Jalali dates.
-- User-supplied raw JSON is TEXT; never expose it through unauthenticated API responses.
CREATE TABLE IF NOT EXISTS channels (
  slug TEXT PRIMARY KEY, name TEXT NOT NULL, category TEXT, kind TEXT,
  icon_url TEXT, source_url TEXT, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS programs (
  program_key TEXT PRIMARY KEY, provider_id TEXT NOT NULL, kind TEXT NOT NULL,
  name TEXT NOT NULL, url TEXT NOT NULL, image_url TEXT, description TEXT,
  season_count INTEGER, raw_json TEXT, updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_programs_name ON programs (name);
CREATE TABLE IF NOT EXISTS program_metadata (
  program_key TEXT PRIMARY KEY REFERENCES programs(program_key),
  source TEXT, details_json TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS program_channels (
  program_key TEXT NOT NULL REFERENCES programs(program_key),
  slug TEXT NOT NULL REFERENCES channels(slug), PRIMARY KEY(program_key,slug)
);
CREATE INDEX IF NOT EXISTS idx_program_channels_slug ON program_channels(slug);
CREATE TABLE IF NOT EXISTS media_items (
  item_key TEXT PRIMARY KEY,
  program_key TEXT NOT NULL REFERENCES programs(program_key),
  kind TEXT NOT NULL CHECK (kind IN ('episode','clip')),
  provider_id TEXT, title TEXT NOT NULL, subtitle TEXT,
  source_url TEXT, image_url TEXT, description TEXT,
  season INTEGER, episode_number INTEGER, duration_seconds INTEGER,
  broadcast_date TEXT, published_at TEXT, view_count BIGINT,
  source_type TEXT, raw_json TEXT, first_seen TEXT NOT NULL, last_seen TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_media_items_program_kind ON media_items(program_key,kind);
CREATE INDEX IF NOT EXISTS idx_media_items_broadcast ON media_items(broadcast_date);
CREATE TABLE IF NOT EXISTS jobs (
  program_key TEXT PRIMARY KEY REFERENCES programs(program_key),
  status TEXT NOT NULL DEFAULT 'pending', attempts INTEGER NOT NULL DEFAULT 0,
  episodes_found INTEGER NOT NULL DEFAULT 0, clips_found INTEGER NOT NULL DEFAULT 0,
  last_error TEXT, started_at TEXT, finished_at TEXT, worker TEXT, updated_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_jobs_status ON jobs(status);
CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TEXT NOT NULL, level TEXT, program_key TEXT, message TEXT, details TEXT
);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
INSERT INTO settings(key,value) VALUES('enabled','0') ON CONFLICT(key) DO NOTHING;
CREATE TABLE IF NOT EXISTS import_history (
  source_sha256 TEXT PRIMARY KEY, source_name TEXT NOT NULL,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), total_rows BIGINT NOT NULL
);
