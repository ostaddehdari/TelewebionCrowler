"""Resume-safe, FK-ordered import of the original 8-table SQLite catalog into PostgreSQL.

Imports exact string JSON/date values and never rewrites existing PostgreSQL records.
Safe to restart and rerun; successful file checksum is recorded only after all tables.
"""
from __future__ import annotations
import argparse
import hashlib
import sqlite3
from pathlib import Path
from psycopg import sql
from .db import connect, initialize

# FK-safe ordering, as defined in the actual October 2026 transfer snapshot.
TABLES = ('channels','programs','program_channels','program_metadata',
          'media_items','jobs','events','settings')
BATCH_SIZE = 750

def digest_file(path: Path) -> str:
    sha = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(4 * 1024 * 1024), b''):
            sha.update(block)
    return sha.hexdigest()

def checked_sqlite(path: Path) -> sqlite3.Connection:
    if not path.is_file() or path.stat().st_size < 100:
        raise ValueError('SQLite source does not exist or is empty')
    with path.open('rb') as handle:
        if handle.read(16) != b'SQLite format 3\x00':
            raise ValueError('Not a SQLite3 database')
    sqlite = sqlite3.connect('file:' + path.resolve().as_posix() + '?mode=ro', uri=True)
    if sqlite.execute('PRAGMA integrity_check').fetchone()[0] != 'ok':
        sqlite.close()
        raise ValueError('SQLite integrity_check failed; do not import this file')
    sqlite.execute('PRAGMA foreign_keys=ON')
    return sqlite

def validate_tables(db: sqlite3.Connection) -> None:
    existing = {row[0] for row in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    missing = set(TABLES) - existing
    if missing:
        raise ValueError('Missing source tables: ' + ', '.join(sorted(missing)))

def clean(row):
    # PostgreSQL TEXT disallows embedded NUL; no JSON re-serialization is performed.
    return tuple(v.replace('\x00','') if isinstance(v,str) else v for v in row)

def transfer_table(source: sqlite3.Connection, dest, table: str, batch_size: int = BATCH_SIZE) -> int:
    fields = [r[1] for r in source.execute('PRAGMA table_info("' + table + '")')]
    cols = sql.SQL(',').join(sql.Identifier(f) for f in fields)
    staging = sql.Identifier('stage_' + table)
    tab = sql.Identifier(table)
    with dest.cursor() as cur:
        cur.execute(sql.SQL('CREATE TEMP TABLE IF NOT EXISTS {} (LIKE {}) ON COMMIT DELETE ROWS').format(staging,tab))
    count = 0
    cursor = source.execute('SELECT * FROM "' + table + '"')
    while rows := cursor.fetchmany(batch_size):
        with dest.transaction():
            with dest.cursor() as cur:
                with cur.copy(sql.SQL('COPY {} ({}) FROM STDIN').format(staging,cols)) as writer:
                    for row in rows:
                        writer.write_row(clean(row))
                cur.execute(sql.SQL('INSERT INTO {} ({}) SELECT {} FROM {} ON CONFLICT DO NOTHING').format(tab,cols,cols,staging))
        count += len(rows)
        if count % (batch_size * 20) < batch_size:
            print(f'  [{table}] read {count:,} source rows',flush=True)
    return count

def run(path: Path, batch_size: int = BATCH_SIZE) -> dict[str,int]:
    if not 1 <= batch_size <= 5000:
        raise ValueError('batch-size must be between 1 and 5000')
    path = path.resolve(strict=True)
    source = checked_sqlite(path)
    try:
        validate_tables(source)
        fingerprint = digest_file(path)
        initialize()
        with connect() as dest:
            dest.autocommit = True
            done = dest.execute('SELECT 1 FROM import_history WHERE source_sha256=%s',(fingerprint,)).fetchone()
            if done:
                print('Already imported: same SHA256 (' + fingerprint[:16] + '...)')
                return {}
            counts = {}
            for table in TABLES:
                print('[IMPORT]',table,flush=True)
                counts[table] = transfer_table(source,dest,table,batch_size)
                print('  completed:',counts[table],flush=True)
            # Make new events generated by PostgreSQL greater than imported events.
            dest.execute("SELECT setval(pg_get_serial_sequence('events','id'), GREATEST((SELECT COALESCE(MAX(id),1) FROM events),1), true)")
            dest.execute('INSERT INTO import_history(source_sha256,source_name,total_rows) VALUES (%s,%s,%s) ON CONFLICT DO NOTHING',
                         (fingerprint,path.name,sum(counts.values())))
            print('[DONE] SHA256:',fingerprint)
            return counts
    finally:
        source.close()

def main():
    ap = argparse.ArgumentParser(description='Import real Telewebion SQLite snapshot into PostgreSQL safely')
    ap.add_argument('sqlite_path',type=Path)
    ap.add_argument('--batch-size',type=int,default=BATCH_SIZE)
    args=ap.parse_args()
    print(run(args.sqlite_path,args.batch_size))

if __name__=='__main__': main()
